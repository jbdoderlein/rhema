//! The `BASH_ENV` init-file provisioner the macros and the MCP wire
//! share.
//!
//! A provisioned function reaches a command through non-interactive
//! bash's `BASH_ENV`: the executor layers the wiring's env map onto
//! every command, a `bash -c` child sources the file named there, and
//! the function is visible in pipelines, substitutions, `set -eu`
//! bodies, and nested `bash -c` children. Four wirings need the same
//! pieces (jobs, vision, search, MCP): a `0700` temp dir, a file whose
//! first line sources the inherited `BASH_ENV` guarded, and an env map
//! that points `BASH_ENV` at the file.
//!
//! Each wiring still owns its function bodies, its own env vars, and
//! the guard that deletes its dir on drop. This module owns the parts
//! whose shape is a reviewed failure mode, once: the header, the
//! inherited-path line, and the mode-0700 directory.

use std::collections::BTreeMap;
use std::ffi::OsString;
use std::path::{Path, PathBuf};

/// The env var non-interactive bash reads its init file from, the one
/// name every provision shares.
pub const VAR_BASH_ENV: &str = "BASH_ENV";

/// Creates a per-process directory under the system temp dir, named
/// `{name}-{pid}-{nanos}` and mode `0700`. The callers own the delete:
/// each wiring removes its directory when its guard drops.
///
/// # Errors
///
/// The directory cannot be created or its mode cannot be set.
pub fn temp_dir(name: &str) -> std::io::Result<PathBuf> {
    let dir = std::env::temp_dir().join(format!(
        "{name}-{}-{}",
        std::process::id(),
        // Nanos of the call: production provisions once per process,
        // but tests provision repeatedly in one process and each dir
        // is owned exclusively by one wiring.
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0)
    ));
    std::fs::create_dir_all(&dir)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700))?;
    }
    Ok(dir)
}

/// Writes `dir/init.bash` and returns its path: the header naming
/// `owner`, the inherited `BASH_ENV` sourced first and guarded, then
/// `body`'s function definitions.
///
/// The inherited file is sourced with `source ... || true` so a user
/// file that sets `set -e` and fails cannot abort the init and leave
/// every provisioned function undefined. Its path is baked into the
/// file, never carried by an env var: the executor layers the map onto
/// every command, so a var would reach every generated init in a chain
/// and an outer one would re-source itself until bash died by signal. A
/// literal path sources exactly once. Provision paths carry no user
/// input; the one quote that could break single quoting is escaped
/// anyway.
///
/// # Errors
///
/// The init file cannot be written.
pub fn write(
    dir: &Path,
    owner: &str,
    inherited: Option<OsString>,
    body: &str,
) -> std::io::Result<PathBuf> {
    let init_path = dir.join("init.bash");
    let mut text = format!("# generated by {owner}; do not edit\n");
    if let Some(inherited) = inherited {
        let quoted = inherited.to_string_lossy().replace('\'', "'\\''");
        text.push_str(&format!("source '{quoted}' || true\n"));
    }
    text.push_str(body);
    std::fs::write(&init_path, text)?;
    Ok(init_path)
}

/// One stub function, newline-terminated: `{name}() { "${bin_var}" {mode}
/// "$@"; }`, the body every macro's init file carries. `args` is the
/// literal tail between the binary and the forwarded arguments: a mode
/// for the macros, `__server <name>` for an MCP stub.
pub fn function(name: &str, bin_var: &str, args: &str) -> String {
    format!("{name}() {{ \"${bin_var}\" {args} \"$@\"; }}\n")
}

/// The env map's `BASH_ENV` entry, pointing at `init_path`.
pub fn bash_env(init_path: &Path) -> (String, String) {
    (
        VAR_BASH_ENV.to_owned(),
        init_path.to_string_lossy().into_owned(),
    )
}

/// A wiring's env map with `BASH_ENV` already set to `init_path`.
pub fn env_with(init_path: &Path) -> BTreeMap<String, String> {
    BTreeMap::from([bash_env(init_path)])
}
